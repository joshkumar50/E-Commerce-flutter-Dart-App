        'orders', jsonb_build_object(
            'total', v_total_orders,
            'pending', v_pending_orders,
            'confirmed', v_confirmed_orders,
            'delivered', v_delivered_orders,
            'cancelled', v_cancelled_orders,
            'total_revenue', v_total_revenue
        ),
