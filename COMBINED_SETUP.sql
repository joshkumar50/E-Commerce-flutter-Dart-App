CREATE OR REPLACE FUNCTION public.rpc_fetch_products_paginated(
    p_category_id TEXT DEFAULT NULL,
    p_search TEXT DEFAULT NULL,
    p_limit INT DEFAULT 20,
    p_offset INT DEFAULT 0,
    p_active_only BOOLEAN DEFAULT TRUE
)
RETURNS TABLE (
    id INT,
    name TEXT,
    description TEXT,
    price NUMERIC,
    unit TEXT,
    image_url TEXT,
    category_id TEXT,
    stock_quantity INT,
